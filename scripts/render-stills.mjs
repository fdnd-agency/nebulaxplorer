// Renders the stills and the hero turn used by /technology without JavaScript.
// usage: node scripts/render-stills.mjs [inspect | stills | locations | hero | all] [name…]
// `locations` also renders the instrument map and writes the label positions
// to src/lib/server/componentViews.js.
// Starts its own Vite server for scripts/render-stills/ (port 5296).
import fs from 'node:fs/promises'
import { createServer } from 'vite'
import { chromium } from 'playwright'
import {
	stills,
	locations,
	instrumentMap,
	hero,
	heroTall,
} from './render-stills/jobs.js'

const [mode = 'all', ...only] = process.argv.slice(2)
const media = new URL('../static/media/', import.meta.url)
const framesRoot = new URL('../.svelte-kit/render-frames/', import.meta.url)
const views = new URL('../src/lib/server/componentViews.js', import.meta.url)

const server = await createServer({
	configFile: new URL(
		'./render-stills/vite.config.js',
		import.meta.url,
	).pathname.replace(/^\/(\w:)/, '$1'),
	logLevel: 'warn',
})
await server.listen()
// A visible window renders with the graphics card; the flags keep it
// rendering while other windows cover it
const browser = await chromium.launch({
	channel: 'chrome',
	headless: false,
	args: [
		'--disable-backgrounding-occluded-windows',
		'--disable-renderer-backgrounding',
		'--disable-background-timer-throttling',
	],
})
const page = await browser.newPage({ viewport: { width: 800, height: 600 } })
page.on('pageerror', (error) => console.error('page error:', error.message))
await page.goto('http://localhost:5296/')
await page.waitForFunction(() => window.stills, null, { timeout: 30000 })
await page.evaluate(() => window.stills.ready)

// Downscales a PNG in the page and encodes WebP files of the given widths
async function encode(png, name, widths) {
	const files = await page.evaluate(
		async ({ png, widths }) => {
			const image = new Image()
			image.src = png
			await image.decode()
			return widths.map((width) => {
				const canvas = document.createElement('canvas')
				canvas.width = width
				canvas.height = Math.round((image.height / image.width) * width)
				const context = canvas.getContext('2d')
				context.imageSmoothingQuality = 'high'
				context.drawImage(image, 0, 0, canvas.width, canvas.height)
				return {
					width,
					height: canvas.height,
					data: canvas.toDataURL('image/webp', 0.86).split(',')[1],
				}
			})
		},
		{ png, widths },
	)
	for (const { width, height, data } of files) {
		const file = new URL(`${name}-${width}.webp`, media)
		await fs.mkdir(new URL('.', file), { recursive: true })
		const buffer = Buffer.from(data, 'base64')
		await fs.writeFile(file, buffer)
		console.log(
			`${name}-${width}.webp`,
			`${width}x${height}`,
			`${Math.round(buffer.length / 1024)} KB`,
		)
	}
}

if (mode === 'inspect') {
	console.log(
		'satellite',
		JSON.stringify(await page.evaluate(() => window.stills.satelliteBox())),
	)
	for (const component of only)
		console.log(
			component,
			JSON.stringify(
				await page.evaluate(
					(c) => window.stills.instances(c),
					component,
				),
				null,
				1,
			),
		)
}

if (mode === 'stills' || mode === 'all') {
	for (const job of stills) {
		if (only.length && !only.includes(job.name)) continue
		const png = await page.evaluate((job) => window.stills.render(job), job)
		await encode(png, `components/${job.name}`, [1200, 640, 320])
	}
}

if (mode === 'locations' || mode === 'all') {
	const data = { locations: {}, map: null }
	for (const job of locations) {
		if (only.length && !only.includes(job.id)) continue
		const { image, anchor } = await page.evaluate(
			(job) => window.stills.location(job),
			job,
		)
		await encode(image, `locations/${job.id}`, [1200, 640])
		data.locations[job.id] = { anchor }
	}
	const { image, anchors } = await page.evaluate(
		(job) => window.stills.map(job),
		instrumentMap,
	)
	await encode(image, `components/${instrumentMap.name}`, [1600, 1200, 640])
	data.map = { anchors }
	// Keep earlier positions when only some locations were rendered again
	const previous = await import(`${views.href}?${Date.now()}`)
		.then((module) => module.componentViews)
		.catch(() => ({ locations: {} }))
	data.locations = { ...previous.locations, ...data.locations }
	await fs.writeFile(
		views,
		`// Generated by scripts/render-stills.mjs locations: where each label points
// in the location views and the instrument map, as fractions of the image
export const componentViews = ${JSON.stringify(data, null, '\t')}
`,
	)
	console.log('label positions in src/lib/server/componentViews.js')
}

// The still is the first frame of the loop, so the start has no jump
async function renderHero(job, name, widths) {
	const last = await page.evaluate(
		(job) =>
			window.stills.turnFrame({
				...job,
				size: job.posterSize,
				progress: 1,
			}),
		job,
	)
	const png = await page.evaluate(async (jpeg) => {
		const image = new Image()
		image.src = jpeg
		await image.decode()
		const canvas = document.createElement('canvas')
		canvas.width = image.width
		canvas.height = image.height
		canvas.getContext('2d').drawImage(image, 0, 0)
		return canvas.toDataURL('image/png')
	}, last)
	await encode(png, `hero/${name}`, widths)
	const frames = new URL(`${name}/`, framesRoot)
	await fs.rm(frames, { recursive: true, force: true })
	await fs.mkdir(frames, { recursive: true })
	const count = Math.round(job.seconds * job.fps)
	for (let index = 0; index < count; index++) {
		const jpeg = await page.evaluate(
			(job) => window.stills.turnFrame(job),
			// The last frame stops one step before the first, so the loop is seamless
			{ ...job, progress: index / count },
		)
		await fs.writeFile(
			new URL(`frame-${String(index).padStart(4, '0')}.jpg`, frames),
			Buffer.from(jpeg.split(',')[1], 'base64'),
		)
	}
	console.log(`${count} frames in .svelte-kit/render-frames/${name}/`)
}

if (mode === 'hero' || mode === 'all') {
	await renderHero(hero, 'satellite', [2160, 1440, 960])
	await renderHero(heroTall, 'satellite-tall', [1350, 900])
}

await browser.close()
await server.close()
