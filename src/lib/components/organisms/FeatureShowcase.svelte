    <h4>More about Quasi-Periodic Oscillations</h4>
    <p>
      Reverberation mapping using X-ray "light echoes" (photons emitted in one
      region of the plasma can either reach the observer directly, or first
      interact with other parts of the plasma, be re-processed and re-emitted at
      different energies, and only then reach the observer), can help us
      understand the geometry and properties of the accreting plasma directly
      surrounding the black hole. Reverberation mapping measures time delays
      between the direct and re-emitted photons and uses these light travel
      delays to reconstruct a map of the accretion flow. Because the reflected
      path is longer, this delay encodes distances at the light-crossing scale
      of the system. Mass and spin come from two different parts of the same
      signal. The overall size of the lag tells us the mass: bigger black holes
      mean bigger gravitational radii, so light takes longer to make the round
      trip. Spin shows-up in how the lag changes with energy across the
      broadened iron K line, because a faster-spinning black hole lets the
      disk’s inner edge sit closer in, shortening the path light must travel
      from the innermost region and reshaping the lag-energy profile. To measure
      this, we need long, near-continuous observations within fine time-tagging
      resolution, sufficient effective area, and energy resolution near the iron
      K line to detect the reverberation signal and resolve the lag-energy
      profile.
    </p>
